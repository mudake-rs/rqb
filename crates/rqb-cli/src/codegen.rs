const GENERATED_PREAMBLE: &str = r#"// @generated by rqb-cli. Do not edit by hand.

//! Generated rqb schema metadata.
//!
//! Relation modules expose typed fields, relation sources, alias handles, and
//! unique constraint names for use with the `rqb` query builder.

#![allow(dead_code)]

"#;
const ROOT_RESERVED_MODULES: &[&str] = &["rqb"];
const RESERVED_TYPE_NAMES: &[&str] = &[
    "BigDecimal",
    "DateTime",
    "FixedOffset",
    "NaiveDate",
    "NaiveDateTime",
    "NaiveTime",
    "PgInterval",
    "PgRange",
    "PgTimeTz",
    "String",
    "Utc",
    "Uuid",
    "Value",
    "Vec",
];

pub(crate) fn render(schema: &SchemaModel) -> Result<String> {
    let module_names = unique_ident_strings(
        schema
            .relations
            .iter()
            .map(|relation| sanitize_ident(&relation.name.to_snake_case())),
        ROOT_RESERVED_MODULES,
    );
    let enum_names = enum_type_names(&schema.enums, &module_names);
    let enum_refs = enum_refs(&schema.enums, &enum_names);
    let type_imports = render_schema_type_imports(&schema.relations);

    let mut code = GENERATED_PREAMBLE.to_owned();
    for import in type_imports {
        code.push_str(&import);
        code.push('\n');
    }
    if !code.ends_with("\n\n") {
        code.push('\n');
    }

    for (enum_type, rust_name) in schema.enums.iter().zip(enum_names.iter()) {
        render_enum(&mut code, enum_type, rust_name);
    }
    if !schema.enums.is_empty() {
        code.push('\n');
    }

    code.push_str("rqb::schema! {\n");
    for (relation, module_name) in schema.relations.iter().zip(module_names.iter()) {
        render_relation(&mut code, relation, module_name, &enum_refs);
    }
    code.push_str("}\n");

    syn::parse_file(&code).context("generated schema code did not parse")?;
    Ok(code)
}

fn render_relation(
    out: &mut String,
    relation: &Relation,
    module_name: &str,
    enum_refs: &BTreeMap<(String, String), String>,
) {
    let kind = match relation.kind {
        RelationKind::Table => "table",
        RelationKind::View | RelationKind::MaterializedView => "view",
    };
    let name = render_relation_name(&relation.schema, &relation.name);
    let default_module = sanitize_ident(&relation.name.to_snake_case());
    let module_alias = if module_name != default_module {
        format!(" as {module_name}")
    } else {
        String::new()
    };

    match relation.kind {
        RelationKind::MaterializedView => out.push_str("    // Materialized view.\n"),
        RelationKind::View if relation.columns.iter().any(|column| column.nullable) => {
            out.push_str("    // View column nullability is conservative in Postgres metadata.\n");
        }
        RelationKind::Table | RelationKind::View => {}
    }
    out.push_str(&format!("    {kind} {name}{module_alias} {{\n"));
    for column in &relation.columns {
        render_column(out, relation.kind, column, enum_refs);
    }
    render_constraints(out, relation);
    out.push_str("    }\n");
}

fn enum_type_names(enums: &[PgEnum], module_names: &[String]) -> Vec<String> {
    let reserved = RESERVED_TYPE_NAMES
        .iter()
        .copied()
        .chain(module_names.iter().map(String::as_str))
        .collect::<Vec<_>>();
    unique_ident_strings(
        enums
            .iter()
            .map(|enum_type| enum_type_ident(&enum_type.name)),
        &reserved,
    )
}

fn enum_refs(enums: &[PgEnum], enum_names: &[String]) -> BTreeMap<(String, String), String> {
    enums
        .iter()
        .zip(enum_names.iter())
        .map(|(enum_type, rust_name)| {
            (
                (enum_type.schema.clone(), enum_type.name.clone()),
                rust_name.clone(),
            )
        })
        .collect()
}

fn render_enum(out: &mut String, enum_type: &PgEnum, rust_name: &str) {
    let type_name = rust_string_literal(&sqlx_type_name(&enum_type.schema, &enum_type.name));
    out.push_str(&format!(
        "/// Rust mapping for PostgreSQL enum `{}`.\n",
        qualified_doc_name(&enum_type.schema, &enum_type.name)
    ));
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, sqlx::Type)]\n");
    out.push_str(&format!("#[sqlx(type_name = {type_name})]\n"));
    out.push_str(&format!("pub enum {rust_name} {{\n"));
    let variant_names = enum_variant_names(&enum_type.variants);
    for (label, variant_name) in enum_type.variants.iter().zip(variant_names.iter()) {
        let label_doc = doc_inline_code(label);
        let label = rust_string_literal(label);
        out.push_str(&format!("    /// PostgreSQL enum label `{}`.\n", label_doc));
        out.push_str(&format!("    #[sqlx(rename = {label})]\n"));
        out.push_str(&format!("    {variant_name},\n"));
    }
    out.push_str("}\n\n");
}

fn enum_variant_names(variants: &[String]) -> Vec<String> {
    unique_ident_strings(
        variants.iter().map(|variant| enum_variant_ident(variant)),
        &[],
    )
}

fn enum_type_ident(name: &str) -> String {
    let ident = sanitize_ident(&name.to_upper_camel_case());
    if ident == "_" {
        "PgEnum".to_owned()
    } else {
        ident
    }
}

fn enum_variant_ident(label: &str) -> String {
    let ident = sanitize_ident(&label.to_upper_camel_case());
    if ident == "_" {
        "Variant".to_owned()
    } else {
        ident
    }
}

fn render_relation_name(schema: &str, relation: &str) -> String {
    if is_plain_ident(schema) && is_plain_ident(relation) {
        format!("{schema}.{relation}")
    } else {
        rust_string_literal(&format!("{schema}.{relation}"))
    }
}

fn render_column(
    out: &mut String,
    relation_kind: RelationKind,
    column: &Column,
    enum_refs: &BTreeMap<(String, String), String>,
) {
    for comment in column_comments(relation_kind, column) {
        out.push_str(&format!("        // {comment}\n"));
    }
    if let ColumnType::Custom { ops, json, .. } = &column.ty {
        out.push_str(&format!(
            "        #[rqb(ops = {}, json = {})]\n",
            ops_attr(*ops),
            json_attr(*json)
        ));
    }
    let name = render_name(&column.name);
    let default_const = sanitize_ident(&column.name.to_shouty_snake_case());
    let const_alias = if column.const_name != default_const {
        format!(" as {}", column.const_name)
    } else {
        String::new()
    };
    let pg = render_name(&column.pg_name());
    let rust_ty = match &column.ty {
        ColumnType::Known(known) => format!(" = {}", rust_type_name(known)),
        ColumnType::Custom { rust, array, .. } => {
            if *array {
                format!(" = Vec<{rust}>")
            } else {
                format!(" = {rust}")
            }
        }
        ColumnType::PgEnum {
            schema,
            name,
            array,
            ..
        } => {
            let rust = enum_refs
                .get(&(schema.clone(), name.clone()))
                .map(String::as_str)
                .expect("PgEnum column must reference a generated enum");
            if *array {
                format!(" = Vec<{rust}>")
            } else {
                format!(" = {rust}")
            }
        }
        ColumnType::RawOnly { .. } => String::new(),
    };
    out.push_str(&format!("        {name}{const_alias}: {pg}{rust_ty},\n"));
}

fn render_constraints(out: &mut String, relation: &Relation) {
    if relation.constraints.is_empty() {
        return;
    }

    out.push_str("        constraints {\n");
    for constraint in &relation.constraints {
        render_constraint(out, constraint);
    }
    out.push_str("        }\n");
}

fn render_constraint(out: &mut String, constraint: &UniqueConstraint) {
    let name = rust_string_literal(&constraint.name);
    out.push_str(&format!("            {}: {name},\n", constraint.const_name));
}

fn ops_attr(ops: FieldOps) -> &'static str {
    match ops {
        FieldOps::None => "none",
        FieldOps::Equality => "equality",
        FieldOps::Ordered => "ordered",
        FieldOps::Text => "text",
    }
}

fn json_attr(json: Option<FieldJson>) -> &'static str {
    match json {
        None => "none",
        Some(FieldJson::Text) => "text",
        Some(FieldJson::Bool) => "bool",
        Some(FieldJson::Integer) => "integer",
        Some(FieldJson::BigInt) => "big_int",
        Some(FieldJson::Float) => "float",
        Some(FieldJson::NumericString) => "numeric_string",
        Some(FieldJson::Uuid) => "uuid",
        Some(FieldJson::Date) => "date",
        Some(FieldJson::Time) => "time",
        Some(FieldJson::Timestamp) => "timestamp",
        Some(FieldJson::Timestamptz) => "timestamptz",
        Some(FieldJson::Jsonb) => "jsonb",
    }
}

fn column_comments(relation_kind: RelationKind, column: &Column) -> Vec<&'static str> {
    let mut comments = Vec::new();
    if column.nullable && relation_kind == RelationKind::Table {
        comments.push("Nullable in Postgres metadata. Use Option<T> in row structs.");
    }
    match column.generated {
        GeneratedKind::None => {}
        GeneratedKind::Stored => {
            comments.push("Generated: stored. Do not include in INSERT assignments.");
        }
        GeneratedKind::IdentityAlways => {
            comments.push(
                "Identity: always. Do not include in INSERT assignments; use OVERRIDING SYSTEM VALUE to override.",
            );
        }
        GeneratedKind::IdentityByDefault => {
            comments.push("Identity: by default. Explicit INSERT values are allowed.");
        }
    }
    comments
}

fn render_name(name: &str) -> String {
    if is_plain_ident(name) {
        name.to_owned()
    } else {
        rust_string_literal(name)
    }
}

impl Column {
    fn pg_name(&self) -> String {
        match &self.ty {
            ColumnType::Known(known) => pg_name(known),
            ColumnType::Custom { pg, .. } => pg.clone(),
            ColumnType::PgEnum { pg, .. } => pg.clone(),
            ColumnType::RawOnly { pg } => pg.clone(),
        }
    }
}

fn rust_type_name(known: &KnownType) -> String {
    match known {
        KnownType::Text | KnownType::Inet | KnownType::Cidr => "String".to_owned(),
        KnownType::Bool => "bool".to_owned(),
        KnownType::Int2 => "i16".to_owned(),
        KnownType::Int4 => "i32".to_owned(),
        KnownType::Int8 => "i64".to_owned(),
        KnownType::Float4 => "f32".to_owned(),
        KnownType::Float8 => "f64".to_owned(),
        KnownType::Numeric => "BigDecimal".to_owned(),
        KnownType::Uuid => "Uuid".to_owned(),
        KnownType::Date => "NaiveDate".to_owned(),
        KnownType::Time => "NaiveTime".to_owned(),
        KnownType::Timetz => "PgTimeTz<NaiveTime, FixedOffset>".to_owned(),
        KnownType::Timestamp => "NaiveDateTime".to_owned(),
        KnownType::Timestamptz => "DateTime<Utc>".to_owned(),
        KnownType::Interval => "PgInterval".to_owned(),
        KnownType::Json | KnownType::Jsonb => "Value".to_owned(),
        KnownType::Bytes => "Vec<u8>".to_owned(),
        KnownType::Range(elem) => format!("PgRange<{}>", rust_type_name(elem)),
        KnownType::Array(elem) => format!("Vec<{}>", rust_type_name(elem)),
    }
}

#[derive(Default)]
struct TypeImports {
    big_decimal: bool,
    date_time: bool,
    fixed_offset: bool,
    naive_date: bool,
    naive_date_time: bool,
    naive_time: bool,
    pg_interval: bool,
    pg_range: bool,
    pg_time_tz: bool,
    serde_value: bool,
    utc: bool,
    uuid: bool,
}

fn render_schema_type_imports(relations: &[Relation]) -> Vec<String> {
    let mut imports = TypeImports::default();
    for relation in relations {
        for column in &relation.columns {
            if let ColumnType::Known(known) = &column.ty {
                collect_type_imports(known, &mut imports);
            }
        }
    }

    let mut rendered = Vec::new();
    let chrono_imports = chrono_imports(&imports);
    if !chrono_imports.is_empty() {
        rendered.push(format!("use chrono::{{{}}};", chrono_imports.join(", ")));
    }
    if imports.serde_value {
        rendered.push("use serde_json::Value;".to_owned());
    }
    let pg_imports = pg_imports(&imports);
    if !pg_imports.is_empty() {
        rendered.push(format!(
            "use sqlx::postgres::types::{{{}}};",
            pg_imports.join(", ")
        ));
    }
    if imports.big_decimal {
        rendered.push("use sqlx::types::BigDecimal;".to_owned());
    }
    if imports.uuid {
        rendered.push("use uuid::Uuid;".to_owned());
    }
    rendered
}

fn collect_type_imports(known: &KnownType, imports: &mut TypeImports) {
    match known {
        KnownType::Text
        | KnownType::Bool
        | KnownType::Int2
        | KnownType::Int4
        | KnownType::Int8
        | KnownType::Float4
        | KnownType::Float8
        | KnownType::Bytes
        | KnownType::Inet
        | KnownType::Cidr => {}
        KnownType::Numeric => imports.big_decimal = true,
        KnownType::Uuid => imports.uuid = true,
        KnownType::Date => imports.naive_date = true,
        KnownType::Time => imports.naive_time = true,
        KnownType::Timetz => {
            imports.pg_time_tz = true;
            imports.naive_time = true;
            imports.fixed_offset = true;
        }
        KnownType::Timestamp => imports.naive_date_time = true,
        KnownType::Timestamptz => {
            imports.date_time = true;
            imports.utc = true;
        }
        KnownType::Interval => imports.pg_interval = true,
        KnownType::Json | KnownType::Jsonb => imports.serde_value = true,
        KnownType::Range(elem) => {
            imports.pg_range = true;
            collect_type_imports(elem, imports);
        }
        KnownType::Array(elem) => collect_type_imports(elem, imports),
    }
}

fn chrono_imports(imports: &TypeImports) -> Vec<&'static str> {
    let mut idents = Vec::new();
    push_import(&mut idents, imports.date_time, "DateTime");
    push_import(&mut idents, imports.fixed_offset, "FixedOffset");
    push_import(&mut idents, imports.naive_date, "NaiveDate");
    push_import(&mut idents, imports.naive_date_time, "NaiveDateTime");
    push_import(&mut idents, imports.naive_time, "NaiveTime");
    push_import(&mut idents, imports.utc, "Utc");
    idents
}

fn pg_imports(imports: &TypeImports) -> Vec<&'static str> {
    let mut idents = Vec::new();
    push_import(&mut idents, imports.pg_interval, "PgInterval");
    push_import(&mut idents, imports.pg_range, "PgRange");
    push_import(&mut idents, imports.pg_time_tz, "PgTimeTz");
    idents
}

fn push_import(idents: &mut Vec<&'static str>, enabled: bool, name: &'static str) {
    if enabled {
        idents.push(name);
    }
}

fn pg_name(known: &KnownType) -> String {
    match known {
        KnownType::Text => "text".to_owned(),
        KnownType::Bool => "bool".to_owned(),
        KnownType::Int2 => "int2".to_owned(),
        KnownType::Int4 => "int4".to_owned(),
        KnownType::Int8 => "int8".to_owned(),
        KnownType::Float4 => "float4".to_owned(),
        KnownType::Float8 => "float8".to_owned(),
        KnownType::Numeric => "numeric".to_owned(),
        KnownType::Uuid => "uuid".to_owned(),
        KnownType::Date => "date".to_owned(),
        KnownType::Time => "time".to_owned(),
        KnownType::Timetz => "timetz".to_owned(),
        KnownType::Timestamp => "timestamp".to_owned(),
        KnownType::Timestamptz => "timestamptz".to_owned(),
        KnownType::Interval => "interval".to_owned(),
        KnownType::Json => "json".to_owned(),
        KnownType::Jsonb => "jsonb".to_owned(),
        KnownType::Bytes => "bytea".to_owned(),
        KnownType::Inet => "inet".to_owned(),
        KnownType::Cidr => "cidr".to_owned(),
        KnownType::Range(elem) => match elem.as_ref() {
            KnownType::Int4 => "int4range".to_owned(),
            KnownType::Int8 => "int8range".to_owned(),
            KnownType::Numeric => "numrange".to_owned(),
            KnownType::Date => "daterange".to_owned(),
            KnownType::Timestamp => "tsrange".to_owned(),
            KnownType::Timestamptz => "tstzrange".to_owned(),
            _ => "range".to_owned(),
        },
        KnownType::Array(elem) => format!("{}[]", pg_name(elem)),
    }
}

fn is_plain_ident(value: &str) -> bool {
    sanitize_ident(value) == value
}

fn rust_string_literal(value: &str) -> String {
    format!("{value:?}")
}

fn qualified_doc_name(schema: &str, name: &str) -> String {
    doc_inline_code(&format!("{schema}.{name}"))
}

fn doc_inline_code(value: &str) -> String {
    value.replace('`', "\\`")
}

fn sqlx_type_name(schema: &str, name: &str) -> String {
    format!("{}.{}", quote_pg_ident(schema), quote_pg_ident(name))
}

fn quote_pg_ident(value: &str) -> String {
    if is_unquoted_pg_ident(value) {
        return value.to_owned();
    }
    format!("\"{}\"", value.replace('"', "\"\""))
}

fn is_unquoted_pg_ident(value: &str) -> bool {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_lowercase() || first == '_') {
        return false;
    }
    chars.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '_')
}

